export function modeHelpOf(id: ModeHelpId): ModeHelp {
  return MODE_HELP[id]
}

/** 主线页签对到说明。旧值 mine 和未知页都算战场。 */
export function modeHelpIdForMainline(tab: string): ModeHelpId {
  if (tab === 'dungeon' || tab === 'market') return tab
  return 'battlefield'
}
